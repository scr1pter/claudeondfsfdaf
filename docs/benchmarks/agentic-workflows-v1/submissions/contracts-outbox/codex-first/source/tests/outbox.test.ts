import { expect, test } from "bun:test"
import { withHarness } from "./support"

test("validation preserves verbatim Unicode bodies and admission is atomic and idempotent", () => withHarness(async h => {
  for (const body of [undefined, null, 1, true, [], {}, "", " \n\t ", "🙂".repeat(2001)]) {
    const first = await h.request("/api/tickets/t-101/messages", "POST", { body }, 400)
    const second = await h.request("/api/tickets/t-101/messages", "POST", { body }, 400)
    expect(first.data.error).toBe(second.data.error)
  }
  await h.request("/api/tickets/t-101/messages", "POST", "{", 400, true)
  for (const value of [null, [], "text", 1]) await h.request("/api/tickets/t-101/messages", "POST", value, 400)
  const unicode = await h.draft("🙂".repeat(2000))
  expect(unicode.body).toBe("🙂".repeat(2000))
  const body = " \n  Synthetic reply 🙂\nwith retained whitespace.  \n"
  const draft = await h.draft(body)
  for (const requestId of [undefined, null, 1, true, "", " ", "a\n", "bad.dot", "é", "a".repeat(81)]) {
    await h.request(`/api/messages/${draft.id}/send`, "POST", { requestId }, 400)
    expect((await h.get(draft.id)).delivery).toBeNull()
  }
  await h.request(`/api/messages/${draft.id}/send`, "POST", "{", 400, true)
  const admissions = await Promise.all(Array.from({ length: 12 }, () => h.admit(draft, "a".repeat(80))))
  const key = admissions[0]!.delivery!.idempotencyKey
  expect(key.length).toBeGreaterThan(0)
  for (const item of admissions) { expect(item.status).toBe("queued"); expect(item.delivery!.idempotencyKey).toBe(key); expect(item.delivery!.attempts).toBe(0); expect(item.body).toBe(body) }
  await h.request(`/api/messages/${draft.id}/send`, "POST", { requestId: "different" }, 409)
  await h.request(`/api/messages/${unicode.id}/send`, "POST", { requestId: "a".repeat(80) }, 409)
  await h.request(`/api/messages/${draft.id}`, "PATCH", { body: "changed" }, 409)
  await h.request(`/api/messages/${unicode.id}`, "PATCH", { body: " " }, 400)
  expect((await h.get(draft.id)).body).toBe(body)
  expect((await h.provider()).attempts).toEqual([])
  expect((await h.request("/api/outbox")).data.items.map((item: any) => item.id)).toEqual([draft.id])
  await h.act(draft.id, "retry")
  const cancelled = await h.act(draft.id, "cancel")
  expect(cancelled.status).toBe("cancelled")
  expect(cancelled.delivery!.cancelRequested).toBe(true)
  await h.act(draft.id, "cancel")
  expect(await h.drain()).toEqual([])
  expect((await h.provider()).attempts).toEqual([])
  await h.request(`/api/messages/${draft.id}/retry`, "POST", {}, 409)
  await h.request(`/api/messages/${unicode.id}/retry`, "POST", {}, 409)
  await h.request("/api/messages/missing", "GET", undefined, 404)
  await h.request("/api/tickets/missing/messages", "POST", { body: "reply" }, 404)
  await h.request("/api/outbox/drain", "POST", "{", 400, true)
}), 30_000)

test("failure, retry, and concurrent drains retain one envelope and one provider effect", () => withHarness(async h => {
  const item = await h.queued("  Synthetic exact body 🙂\n  ")
  await h.control("plan", { messageId: item.id, mode: "fail_once" })
  expect(await h.drain()).toEqual([item.id])
  const failed = await h.get(item.id)
  expect(failed.status).toBe("retryable")
  expect(failed.delivery!.attempts).toBe(1)
  expect(failed.delivery!.receiptId).toBeNull()
  expect(failed.delivery!.lastError).toBeTruthy()
  expect(await h.drain()).toEqual([])
  expect((await h.get(item.id)).delivery!.attempts).toBe(1)
  await h.act(item.id, "retry")
  await h.act(item.id, "retry")
  await Promise.all(Array.from({ length: 12 }, () => h.drain()))
  const delivered = await h.get(item.id)
  expect(delivered.status).toBe("delivered")
  expect(delivered.delivery!.attempts).toBe(2)
  expect(delivered.delivery!.idempotencyKey).toBe(item.delivery!.idempotencyKey)
  expect(delivered.delivery!.receiptId).toBeTruthy()
  expect(delivered.delivery!.lastError).toBeNull()
  const state = await h.provider()
  expect(state.receipts.length).toBe(1)
  expect(state.receipts[0]!.body).toBe(item.body)
  expect(state.attempts.length).toBe(2)
  expect((await h.admit(item)).delivery).toEqual(delivered.delivery)
  await h.request(`/api/messages/${item.id}/retry`, "POST", {}, 409)
  expect(await h.drain()).toEqual([])
  await h.stop(); await h.start()
  expect((await h.get(item.id)).delivery).toEqual(delivered.delivery)
  expect((await h.provider()).receipts.length).toBe(1)
}), 30_000)

test("cancellation before provider acceptance tombstones the key and late send cannot revive it", () => withHarness(async h => {
  const item = await h.queued()
  await h.control("plan", { messageId: item.id, mode: "before_accept" })
  const drain = h.drain()
  await h.held(item.id)
  const cancelled = await h.act(item.id, "cancel")
  expect(cancelled.status).toBe("cancelled")
  expect(cancelled.delivery!.attempts).toBe(1)
  expect(cancelled.delivery!.receiptId).toBeNull()
  await drain
  expect((await h.get(item.id)).status).toBe("cancelled")
  expect((await h.provider()).receipts).toEqual([])
  await h.stop(); await h.start()
  expect((await h.get(item.id)).status).toBe("cancelled")
  expect(await h.drain()).toEqual([])
}), 30_000)

test("cancellation after provider acceptance exposes receipt and retains too-late explanation", () => withHarness(async h => {
  const item = await h.queued()
  await h.control("plan", { messageId: item.id, mode: "after_accept" })
  const drain = h.drain()
  const held = await h.held(item.id)
  expect(held.receipts.length).toBe(1)
  const cancelled = await h.act(item.id, "cancel")
  expect(cancelled.status).toBe("delivered")
  expect(cancelled.delivery!.receiptId).toBe(held.receipts[0]!.id)
  expect(cancelled.delivery!.lastError).toContain("too late")
  // A provider may release a held request on cancellation; otherwise explicitly release it.
  await h.control("release", { messageId: item.id, response: "lost" })
  await drain
  expect((await h.get(item.id)).delivery).toEqual(cancelled.delivery)
  await h.act(item.id, "cancel")
  await h.stop(); await h.start()
  expect((await h.get(item.id)).delivery).toEqual(cancelled.delivery)
}), 30_000)

test("transient cancellation stays unresolved and a later drain finishes cancellation", () => withHarness(async h => {
  const item = await h.queued()
  await h.control("plan", { messageId: item.id, mode: "reject" })
  await h.drain()
  await h.control("cancel-plan", { idempotencyKey: item.delivery!.idempotencyKey, mode: "fail_once" })
  const unresolved = await h.act(item.id, "cancel")
  expect(unresolved.status).toBe("retryable")
  expect(unresolved.delivery!.cancelRequested).toBe(true)
  expect(unresolved.delivery!.lastError).toContain("Cancellation unresolved")
  expect((await h.provider()).cancellations).toEqual([])
  await h.stop(); await h.start()
  expect((await h.get(item.id)).delivery).toEqual(unresolved.delivery)
  await h.act(item.id, "retry")
  await h.drain()
  const cancelled = await h.get(item.id)
  expect(cancelled.status).toBe("cancelled")
  expect(cancelled.delivery!.idempotencyKey).toBe(item.delivery!.idempotencyKey)
  expect(cancelled.delivery!.attempts).toBe(1)
  expect((await h.provider()).receipts).toEqual([])
}), 30_000)

test("lost receipt is reconciled by replay with the same provider key", () => withHarness(async h => {
  const item = await h.queued()
  await h.control("plan", { messageId: item.id, mode: "after_accept" })
  const drain = h.drain()
  const accepted = await h.held(item.id)
  await h.control("release", { messageId: item.id, response: "lost" })
  await drain
  const unknown = await h.get(item.id)
  expect(unknown.status).toBe("retryable")
  expect(unknown.delivery!.receiptId).toBeNull()
  expect(unknown.delivery!.lastError).toBeTruthy()
  await h.control("plan", { messageId: item.id, mode: "accept" })
  await h.act(item.id, "retry")
  await h.drain()
  const delivered = await h.get(item.id)
  expect(delivered.status).toBe("delivered")
  expect(delivered.delivery!.receiptId).toBe(accepted.receipts[0]!.id)
  expect(delivered.delivery!.idempotencyKey).toBe(item.delivery!.idempotencyKey)
  expect((await h.provider()).receipts.length).toBe(1)
}), 30_000)

test("hard stop after provider acceptance recovers unfinished work without duplicate effect", () => withHarness(async h => {
  const item = await h.queued()
  await h.control("plan", { messageId: item.id, mode: "after_accept" })
  const interrupted = h.drain().catch(() => [])
  const accepted = await h.held(item.id)
  expect((await h.get(item.id)).status).toBe("sending")
  await h.stop(); await interrupted; await h.start()
  const restored = await h.get(item.id)
  expect(["sending", "queued", "retryable"]).toContain(restored.status)
  expect(restored.delivery!.attempts).toBe(1)
  expect(restored.delivery!.idempotencyKey).toBe(item.delivery!.idempotencyKey)
  expect((await h.provider()).attempts.length).toBe(1)
  await h.control("plan", { messageId: item.id, mode: "accept" })
  expect(await h.drain()).toEqual([item.id])
  const recovered = await h.get(item.id)
  expect(recovered.status).toBe("delivered")
  expect(recovered.delivery!.receiptId).toBe(accepted.receipts[0]!.id)
  expect(recovered.delivery!.attempts).toBe(2)
  expect((await h.provider()).receipts.length).toBe(1)
}), 30_000)

