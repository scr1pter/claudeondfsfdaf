test("each drain uses a stable admission snapshot and draft cancellation is local", () => withHarness(async h => {
  const first = await h.queued()
  await h.control("plan", { messageId: first.id, mode: "before_accept" })
  const drain = h.drain()
  await h.held(first.id)
  const next = await h.queued("Synthetic reply admitted during a drain")
  const local = await h.draft("Synthetic draft cancellation")
  expect((await h.act(local.id, "cancel")).status).toBe("cancelled")
  expect((await h.get(local.id)).delivery).toBeNull()
  const cancelledNext = await h.queued("Synthetic cancellation during another attempt")
  expect((await h.act(cancelledNext.id, "cancel")).status).toBe("cancelled")
  await h.control("release", { messageId: first.id, response: "receipt" })
  expect(await drain).toEqual([first.id])
  expect((await h.get(next.id)).status).toBe("queued")
  expect((await h.get(next.id)).delivery!.attempts).toBe(0)
  expect(await h.drain()).toEqual([next.id])
  expect((await h.provider()).receipts.length).toBe(2)
  expect((await h.request("/api/tickets/t-101")).data.messages.map((item: any) => item.id)).toEqual([first.id, next.id, local.id, cancelledNext.id])
  expect((await h.request("/api/outbox")).data.items.map((item: any) => item.id)).toEqual([first.id, next.id, cancelledNext.id])
}), 30_000)
