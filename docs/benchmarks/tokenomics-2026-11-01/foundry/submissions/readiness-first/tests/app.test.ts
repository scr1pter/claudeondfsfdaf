async function call(who: string, path: string, method = 'GET', body?: any, status = 200) {
  const headers: Record<string, string> = {};
  if (cookies[who]) headers.Cookie = cookies[who];
  if (body !== undefined && !(body instanceof FormData)) headers['Content-Type'] = 'application/json';
  const res = await app.fetch(new Request('http://127.0.0.1' + path, { method, headers, body: body === undefined ? undefined : body instanceof FormData ? body : JSON.stringify(body) }));
  const value = res.status === 204 ? null : res.headers.get('content-type')?.includes('json') ? await res.json() : await res.text();
  expect(res.status, `${method} ${path}: ${JSON.stringify(value)}`).toBe(status);
  if (res.headers.get('set-cookie')) cookies[who] = res.headers.get('set-cookie')!.split(';')[0];
  if (status >= 400) { expect(value.error.code).toBeTruthy(); expect(value.error.message).toBeTruthy(); }
  return { body: value as R, res };
}
