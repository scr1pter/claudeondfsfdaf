class Client {
  cookie = '';
  constructor(public workspace = '') {}
  async request(method: string, path: string, body?: unknown, status = 200) {
    const headers: Record<string, string> = {};
    if (this.cookie) headers.cookie = this.cookie;
    if (body !== undefined && !(body instanceof FormData)) headers['content-type'] = 'application/json';
    const response = await fetch(base + path, {
      method, headers,
      body: body === undefined ? undefined : body instanceof FormData ? body : JSON.stringify(body),
      redirect: 'manual',
    });
    const cookie = response.headers.get('set-cookie');
    if (cookie) this.cookie = cookie.split(';')[0];
    const text = await response.text();
    let json: any;
    try { json = text ? JSON.parse(text) : undefined; } catch { json = text; }
    check(response.status === status, `${method} ${path}: expected ${status}, got ${response.status}: ${text.slice(0, 500)}`);
    if (status >= 400) check(json?.error?.code && json?.error?.message, 'Structured JSON error required');
    if (status === 204) check(text === '', '204 must have no response body');
    return { body: json, response, text };
  }
  async w(method: string, path: string, body?: unknown, status = 200) {
    return this.request(method, `/api/w/${this.workspace}${path}`, body, status);
  }
}
