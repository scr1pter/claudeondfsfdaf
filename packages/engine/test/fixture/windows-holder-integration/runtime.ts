import { createHash } from "node:crypto"
import { lstat, mkdtemp, readFile, realpath, rm, rmdir, writeFile } from "node:fs/promises"
import path from "node:path"
import { integrationRunner } from "./scope"

type Holder = { executable: string; release(): Promise<void> }
const maximumBytes = 1_048_576

export class IntegrationHolderDeadline extends Error {}

/** The caller uses this same absolute deadline for verified staging, launch and the real ready frame. */
export async function prepareIntegrationHolder(deadline: number): Promise<Holder> {
  const remaining = deadline - performance.now()
  if (remaining <= 0) throw new IntegrationHolderDeadline()
  const pending = materialize()
  let timer: ReturnType<typeof setTimeout> | undefined
  try {
    const prepared = await Promise.race([
      pending,
      new Promise<never>((_, reject) => {
        timer = setTimeout(
          () => reject(new IntegrationHolderDeadline()),
          Math.max(0, Math.ceil(deadline - performance.now())),
        )
      }),
    ])
    if (performance.now() >= deadline) throw new IntegrationHolderDeadline()
    return prepared
  } catch (error) {
    // A filesystem operation may finish after the watchdog. Only cleanup may use its late result.
    void pending.then(
      (holder) => holder.release(),
      () => {},
    )
    throw error
  } finally {
    clearTimeout(timer)
  }
}

async function materialize(): Promise<Holder> {
  const context = integrationRunner()
  if (
    !(await lstat(context.temporary)).isDirectory() ||
    (await realpath(context.temporary)).toLowerCase() !== context.temporary.toLowerCase()
  ) {
    throw new Error("Invalid integration holder staging root")
  }
  // The fixed file is generated by the owned diagnostic job from its paired artifact. Nothing can select a path here.
  const { asset } = await import(new URL("./asset.generated.ts", import.meta.url).href)
  if (
    asset.run !== context.run ||
    asset.attempt !== context.attempt ||
    asset.revision !== context.revision ||
    typeof asset.base64 !== "string" ||
    asset.base64.length > Math.ceil(maximumBytes / 3) * 4 ||
    typeof asset.sha256 !== "string" ||
    !/^[a-f0-9]{64}$/.test(asset.sha256)
  ) {
    throw new Error("Invalid embedded integration holder")
  }
  const bytes = Buffer.from(asset.base64, "base64")
  if (!bytes.length || bytes.length > maximumBytes || hash(bytes) !== asset.sha256)
    throw new Error("Invalid embedded integration holder bytes")

  const directory = await mkdtemp(path.win32.join(context.temporary, "vector-direct-holder-integration-"))
  const executable = path.win32.join(directory, "holder.exe")
  const release = async () => {
    await rm(executable, { force: true }).catch(() => {})
    await rmdir(directory).catch(() => {})
  }
  try {
    if ((await realpath(directory)).toLowerCase() !== directory.toLowerCase())
      throw new Error("Invalid integration holder staging path")
    await writeFile(executable, bytes, { flag: "wx" })
    const info = await lstat(executable)
    if (!info.isFile() || info.nlink !== 1 || info.size !== bytes.length)
      throw new Error("Invalid staged integration holder")
    if (hash(await readFile(executable)) !== asset.sha256) throw new Error("Staged integration holder hash changed")
    return { executable, release }
  } catch (error) {
    await release()
    throw error
  }
}

function hash(bytes: Uint8Array) {
  return createHash("sha256").update(bytes).digest("hex")
}
