import { $ } from "bun"
import { describe, expect, test } from "bun:test"
import fs from "node:fs/promises"
import path from "node:path"
import { sql } from "drizzle-orm"
import { Effect, Layer } from "effect"
import { CrossSpawnSpawner } from "@vectordevai/core/cross-spawn-spawner"
import { LayerNode } from "@vectordevai/core/effect/layer-node"
import { Database } from "@vectordevai/core/database/database"
import { ReviewAuthor } from "@/review/author"
import { testEffect } from "../lib/effect"
import { tmpdirScoped } from "../fixture/fixture"
import { directory, file, first, last, lookupFixture, middle, seedAuthorship, session } from "../fixture/review-author"

const it = testEffect(Layer.merge(Database.layerFromPath(":memory:"), LayerNode.compile(CrossSpawnSpawner.node)))
const native = process.platform === "linux" ? it.live : it.live.skip

describe("trusted local authorship", () => {
  test("normalizes only labelled claims and does not turn claims or serialized proofs into authority", () => {
    const claimedAuthor = ReviewAuthor.claims({
      branch: "codex/feature",
      body: "ordinary text mentions Gemini\nGenerated by Claude Code",
      trailers: "Gemini <some-address.invalid>",
    })
    expect(claimedAuthor).toEqual([
      { source: "branch", lab: "openai" },
      { source: "pr-body", lab: "anthropic" },
      { source: "trailer", lab: "google" },
    ])
    expect(ReviewAuthor.trustedLab({ claimedAuthor } as unknown as ReviewAuthor.Proof)).toBeUndefined()
  })

  it.live("requires a complete ordered same-lab chain with exact paths in unfenced local SQLite history", () =>
    Effect.gen(function* () {
      const write = yield* seedAuthorship(directory)
      const { db } = yield* Database.Service
      const lab = (paths?: string[]) =>
        lookupFixture(paths).pipe(
          Effect.map((result) => ReviewAuthor.trustedLab("proof" in result ? result.proof : undefined)),
        )
      expect(yield* lab()).toBeUndefined()
      yield* write(0, first, middle)
      yield* write(1, middle, last)
      expect(yield* lab()).toBe("anthropic")
      expect(yield* lab(["different.ts"])).toBeUndefined()
      yield* db.run(sql`UPDATE session_message SET data=json_set(data,'$.model.id','gpt-5') WHERE seq=0`)
      expect(yield* lab()).toBeUndefined()
      yield* db.run(sql`UPDATE session_message SET data=json_set(data,'$.model.id','claude-sonnet') WHERE seq=0`)
      yield* db.run(sql`UPDATE session_audience SET guest_input=1 WHERE session_id=${session}`)
      expect(yield* lab()).toBeUndefined()
      yield* db.run(sql`UPDATE session_audience SET guest_input=0 WHERE session_id=${session}`)
      yield* db.run(sql`INSERT INTO review_memory_fence(session_id,version) VALUES (${session},1)`)
      expect(yield* lab()).toBeUndefined()
      yield* db.run(sql`DELETE FROM review_memory_fence WHERE session_id=${session}`)
      yield* write(2, first, last)
      expect(yield* lab()).toBeUndefined()
    }),
  )

  native(
    "binds V2 snapshots to both actual commit trees and ignores forged commit trailers",
    () =>
      Effect.gen(function* () {
        const root = yield* tmpdirScoped({ git: true })
        const git = (...args: string[]) =>
          Effect.promise(() => $`git ${args}`.cwd(root).quiet().text()).pipe(Effect.map((out) => out.trim()))
        const base = yield* git("rev-parse", "HEAD")
        const before = yield* git("rev-parse", "HEAD^{tree}")
        yield* Effect.promise(() => fs.mkdir(path.join(root, "src")))
        yield* Effect.promise(() => fs.writeFile(path.join(root, file), "export const n = 1\n"))
        yield* git("add", "--", file)
        yield* git("commit", "-m", "Record change", "-m", "Co-authored-by: GPT <fake@example.invalid>")
        const head = yield* git("rev-parse", "HEAD")
        const after = yield* git("rev-parse", "HEAD^{tree}")
        const write = yield* seedAuthorship(root, base)
        const lookup = ReviewAuthor.lookup({ directory: root, base, head, paths: [file] })
        const claim = yield* lookup
        expect(claim.claimedAuthor).toContainEqual({ source: "trailer", lab: "openai" })
        expect("proof" in claim && claim.proof).toBeFalsy()
        yield* write(0, before, after)
        const result = yield* lookup
        expect(ReviewAuthor.trustedLab("proof" in result ? result.proof : undefined)).toBe("anthropic")
      }),
    30_000,
  )
})
