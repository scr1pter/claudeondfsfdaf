// Written into every job as VECTOR_WORKFLOW_VERSION; the CLI asks for a reinstall when a workflow's differs. It stays
// "2" while the CLI and the desktop install this v2 workflow; GithubAgents.WORKFLOW_VERSION is the v3 builder's.
export const GITHUB_WORKFLOW_VERSION = "2"

export interface WorkflowOptions {
  provider: string
  model: string
  keys: readonly string[] // the provider's key variables, passed through from same-named repository secrets
  autoReview: boolean
  auth?: "github" | "auto" | "app" // App mode is an explicit workflow-owner opt-in
  share?: boolean // explicit owner consent to publish task conversations and future updates
  monthlyUsd?: number // REVIEW_MAX_COST_USD_PER_MONTH; written for paid models only
  version: string // the CLI version to pin
  mentions?: readonly string[] // baked into the route job; Vectorscope mentions and legacy aliases by default
}

// Development builds pin the CLI version the desktop release requires instead of a moving registry tag. The desktop
// version itself is not always on npm: a desktop release can ship while the CLI stays at an earlier version.
export function cliVersionSpec(version: string): { spec: string; pinned: boolean } {
  const pinned = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.]+)?$/.test(version) && !version.startsWith("0.0.0")
  return { spec: pinned ? version : release.vectorRequiredCliVersion, pinned: true }
}

// The route job's script for actions/github-script. It embeds core's parser, so the route job and the CLI can never
// disagree about what a comment asks for.
export function buildRouteScript(mentions: readonly string[] = DEFAULT_MENTIONS, app = false): string {
  const script = [
    "// Generated by `vector github install` from parseReviewCommand. Do not edit by hand.",
    `const parseReviewCommand = ${parseReviewCommand.toString()}`,
    `const mentions = ${JSON.stringify(mentions)}`,
    `const PAUSED = ${JSON.stringify(PAUSED_LABEL)}`,
    'const WRITERS = ["admin", "maintain", "write"]',
    "const { owner, repo } = context.repo",
    "const payload = context.payload",
    "",
    "function output(kind, pr, ref) {",
    '  core.setOutput("kind", kind)',
    '  core.setOutput("pr", pr ? String(pr) : "")',
    '  core.setOutput("ref", ref || "")',
    '  core.info("kind=" + kind + " pr=" + (pr || "") + " ref=" + (ref || ""))',
    "}",
    "",
    "// A fork's code is never checked out: its review starts from the merge-base and reads the pull request's",
    "// files from git objects.",
    "async function resolveRef(pr) {",
    "  const { data: pull } = await github.rest.pulls.get({ owner, repo, pull_number: pr })",
    ...(app
      ? [
          '  const eligible = ["issue_comment", "workflow_dispatch"].includes(context.eventName) && pull.head.repo && pull.head.repo.id === pull.base.repo.id',
          '  core.setOutput("app", eligible ? "true" : "false")',
        ]
      : []),
    "  if (pull.head.repo && pull.head.repo.full_name === pull.base.repo.full_name) return pull.head.sha",
    "  try {",
    "    const { data } = await github.rest.repos.compareCommitsWithBasehead({",
    "      owner,",
    "      repo,",
    '      basehead: pull.base.sha + "..." + pull.head.sha,',
    "      per_page: 1,",
    "    })",
    "    if (data.merge_base_commit && data.merge_base_commit.sha) return data.merge_base_commit.sha",
    "  } catch (error) {",
    '    core.warning("compare failed (" + (error.status || error.message) + "); starting from the base commit")',
    "  }",
    "  return pull.base.sha",
    "}",
    "",
    'if (context.eventName === "workflow_dispatch") {',
    "  const pr = Number(payload.inputs && payload.inputs.pr)",
    "  if (!Number.isInteger(pr) || pr < 1) {",
    '    core.setFailed("inputs.pr must be a pull request number")',
    '    return output("none")',
    "  }",
    '  return output("review", pr, await resolveRef(pr))',
    "}",
    "",
    "const comment = payload.comment",
    'if (!comment || (comment.user && comment.user.type === "Bot")) return output("none")',
    'const reviewComment = context.eventName === "pull_request_review_comment"',
    "const number = reviewComment ? payload.pull_request.number : payload.issue.number",
    'const kind = parseReviewCommand(comment.body || "", mentions).kind',
    'if (kind === "none" || kind === "dismiss") return output("none")',
    "// A review verb on an issue that is not a pull request does nothing; a task works on issues too.",
    'if (kind !== "task" && !reviewComment && !payload.issue.pull_request) return output("none")',
    "",
    "function react(content) {",
    "  const target = { owner, repo, comment_id: comment.id, content }",
    "  return reviewComment",
    "    ? github.rest.reactions.createForPullRequestReviewComment(target)",
    "    : github.rest.reactions.createForIssueComment(target)",
    "}",
    "",
    "// Only people with write access get a runner, for a task as for a review, so nobody else can start the task job",
    "// or take a writer's place in its queue. Any error counts as no.",
    "let writer = false",
    "try {",
    "  const { data } = await github.rest.repos.getCollaboratorPermissionLevel({ owner, repo, username: comment.user.login })",
    "  writer = WRITERS.includes(data.role_name) || WRITERS.includes(data.permission)",
    "} catch (error) {",
    '  core.warning("permission check failed for " + comment.user.login + ": " + (error.status || error.message))',
    "}",
    "if (!writer) {",
    '  await react("confused").catch(() => {})',
    '  return output("none")',
    "}",
    ...(app
      ? [
          'if (kind === "task" && (reviewComment || payload.issue.pull_request)) {',
          "  const { data: pull } = await github.rest.pulls.get({ owner, repo, pull_number: number })",
          "  if (!pull.head.repo || pull.head.repo.id !== pull.base.repo.id) {",
          '    core.warning("Vector App tasks cannot execute fork pull requests; use the fork-safe review command.")',
          '    return output("none")',
          "  }",
          "}",
        ]
      : []),
    'if (kind === "task") return output("task", number)',

    'if (kind === "pause") {',
    "  await github.rest.issues.addLabels({ owner, repo, issue_number: number, labels: [PAUSED] })",
    '  await react("+1")',
    '  return output("none")',
    "}",
    'if (kind === "resume") {',
    "  try {",
    "    await github.rest.issues.removeLabel({ owner, repo, issue_number: number, name: PAUSED })",
    "  } catch (error) {",
    "    if (error.status !== 404) throw error",
    "  }",
    '  await react("+1")',
    '  return output("none")',
    "}",
    "return output(kind, number, await resolveRef(number))",
  ].join("\n")
  // Actions evaluates `${{ … }}` anywhere in `with:`, so the script must never contain one.
  if (script.includes("${{")) throw new Error("The route script contains an Actions expression")
  return script
}

