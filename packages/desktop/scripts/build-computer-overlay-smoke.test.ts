import { describe, expect, test } from "bun:test"
import {
  computerOverlayBundlePlan,
  computerOverlayCmakePins,
  computerOverlayPinValues,
  computerOverlaySwiftIdentity,
  parseComputerOverlayBuildOptions,
} from "./build-computer-overlay-smoke"
const inputs = {
  sourceDigest: "a".repeat(64),
  electronVersion: "42.11.4",
  electron: Buffer.from("actual electron"),
  main: Buffer.from("actual main"),
  preload: Buffer.from("actual preload"),
  fakeHelper: Buffer.from("actual fake"),
  defaultApp: Buffer.from("actual default app"),
}
describe("finite never-shipped overlay build contracts", () => {
  test("accepts only the actual native platform and fixed helper/output arguments", () => {
    expect(
      parseComputerOverlayBuildOptions(["--platform", "darwin", "--out", "/tmp/overlay", "--helper", "/tmp/helper"])
        .platform,
    ).toBe("darwin")
    for (const args of [
      ["--platform", "linux", "--out", "/tmp/o", "--helper", "/tmp/h"],
      ["--out", "/tmp/o"],
      ["--out", "/tmp/o", "--helper", "/tmp/h", "--script", "other.mjs"],
    ])
      expect(() => parseComputerOverlayBuildOptions(args)).toThrow()
  })
  test("compiles the fixed main, sandboxed preload and fake helper into the exact native-admitted filenames", () => {
    const output = "/tmp/private-overlay-stage/smoke"
    const plans = computerOverlayBundlePlan("/workspace/vector/packages/desktop", output, inputs.sourceDigest)
    expect(plans.map(({ options }) => [options.naming, options.format])).toEqual([
      ["computer-overlay-smoke-electron.mjs", "esm"],
      ["computer-overlay-smoke-preload.cjs", "cjs"],
      ["computer-fake-helper.mjs", "esm"],
    ])
    for (const { options } of plans) {
      expect(options.outdir).toBe(output)
      expect(options).not.toHaveProperty("outfile")
      expect(options.target).toBe("node")
      expect(options.external).toEqual(["electron"])
      expect(options.allowUnresolved).toEqual([])
      expect(options.define).toEqual({ VECTOR_COMPUTER_SMOKE_SOURCE_DIGEST: JSON.stringify(inputs.sourceDigest) })
    }
    expect(
      computerOverlayBundlePlan("/workspace/vector/packages/desktop", output).every(
        ({ options }) => Object.keys(options.define).length === 0,
      ),
    ).toBe(true)
    expect(() => computerOverlayBundlePlan("/workspace/vector/packages/desktop", output, "unmeasured")).toThrow()
  })
  test("derives immutable driver pins from exact generated bytes", () => {
    const before = computerOverlayPinValues(inputs),
      after = computerOverlayPinValues({ ...inputs, main: Buffer.from("different generated main") })
    expect(before.mainSha256).not.toBe(after.mainSha256)
    expect(before.preloadSha256).toBe(after.preloadSha256)
    expect(Object.values(before).filter((value) => /^[a-f0-9]{64}$/.test(value))).toHaveLength(6)
  })
  test("Swift and CMake identities carry all actual pins without runtime replacements", () => {
    const pins = computerOverlayPinValues(inputs),
      swift = computerOverlaySwiftIdentity(pins),
      cmake = computerOverlayCmakePins(pins)
    for (const value of Object.values(pins)) expect(swift).toContain(value)
    expect(cmake).toContain("-DVECTOR_COMPUTER_OVERLAY_DRIVER=ON")
    expect(cmake).toContain(`-DVECTOR_OVERLAY_MAIN_SHA256=${pins.mainSha256}`)
    expect(cmake).toContain(`-DVECTOR_COMPUTER_SOURCE_DIGEST=${pins.sourceDigest}`)
    expect(cmake.some((argument) => /(?:path|script|command)=/i.test(argument))).toBe(false)
  })
  test("missing native/source versions and missing generated bytes cannot produce identity pins", () => {
    for (const changed of [
      { sourceDigest: "unmeasured" },
      { electronVersion: "latest" },
      { main: Buffer.alloc(0) },
      { fakeHelper: Buffer.alloc(0) },
    ])
      expect(() => computerOverlayPinValues({ ...inputs, ...changed })).toThrow()
  })
})
