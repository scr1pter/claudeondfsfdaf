private func unitProgress(_ message: String) {
    // Fixed, small stderr records bypass buffered stdout and never include an assertion or OS payload.
    let bytes = Array((message + "\n").utf8)
    _ = bytes.withUnsafeBytes { buffer in
        Darwin.write(STDERR_FILENO, buffer.baseAddress, buffer.count)
    }
}

